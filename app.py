def excel_safe(v):
    # Excel runs cells that start with = + - @ as formulas; customers type names and notes, so neutralise those.
    v = "" if v is None else str(v)
    if re.fullmatch(r"[+-][0-9 ().-]*", v): return f'="{v}"'  # phone numbers like +1 619...: text, shown exactly as typed
    return "'" + v if v[:1] in ("=", "+", "-", "@", "\t", "\r") else v

