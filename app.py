def admin_product_save(h, pid=None):
    f, new = h.form, pid is None
    try:
        stock = int(f.get("stock") or -1)
        vals = (f.get("sku", "").strip(), f.get("name", "").strip(), f.get("description", "").strip(),
                cents(f.get("retail", "")), cents(f.get("wholesale", "")), stock,
                int("wholesale_only" in f), int("active" in f))
        if not (vals[0] and vals[1]) or stock < 0: raise ValueError("SKU, name and a stock of 0 or more are required.")
        with h.c:
            # shortcut: stock is set, not adjusted, so an order placed while this form was open is overwritten; add a "received +N" field if that bites
            if pid: h.c.execute("UPDATE products SET sku=?,name=?,description=?,retail_cents=?,wholesale_cents=?,stock=?,"
                                "wholesale_only=?,active=? WHERE id=?", (*vals, pid))
            else: pid = h.c.execute("INSERT INTO products(sku,name,description,retail_cents,wholesale_cents,stock,"
                                    "wholesale_only,active) VALUES(?,?,?,?,?,?,?,?) RETURNING id", vals).fetchone()["id"]
            if f.get("image_data"):
                old = h.c.execute("SELECT image_id FROM products WHERE id=?", (pid,)).fetchone()["image_id"]
                h.c.execute("UPDATE products SET image_id=? WHERE id=?", (save_image(h.c, f["image_data"], "product"), pid))
                if old: h.c.execute("DELETE FROM images WHERE id=?", (old,))
            log(h.c, h.user["id"], "product.save", f"product {pid} {vals[0]}: retail {money(vals[3])}, wholesale "
                f"{money(vals[4])}, stock {stock}, {'wholesale only' if vals[6] else 'public'}, {'active' if vals[7] else 'inactive'}")
    except (ValueError, psycopg.errors.UniqueViolation) as ex:
        msg = "That SKU is already used." if isinstance(ex, psycopg.errors.UniqueViolation) else str(ex)
        return admin_products(h, msg) if new else admin_product(h, pid, msg)  # a failed new product was rolled back
    h.redirect("/admin/products")

