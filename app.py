def admin_export_csv(h, name):
    if name not in EXPORTS: return h.page("Not found", "<p>No such export.</p>", 404)
    title, sql = EXPORTS[name]
    cur = h.c.execute(sql, (str(TZ),) if "?" in sql else None)
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow([col.name for col in cur.description])
    w.writerows([excel_safe(v) for v in row.values()] for row in cur)
    with h.c: log(h.c, h.user["id"], "export", f"{name}.csv")
    stamp = datetime.now(TZ).strftime("%Y-%m-%d")
    h.send(200, "\ufeff" + buf.getvalue(), ctype="text/csv; charset=utf-8",  # BOM so Excel reads accents correctly
           headers=[("Content-Disposition", f'attachment; filename="{name}-{stamp}.csv"'), ("Cache-Control", "no-store")])

