class H(BaseHTTPRequestHandler):
    def do_GET(self): self.route("GET")
    def do_POST(self): self.route("POST")

    def route(self, method):
        self.c = db()
        try:
            url = urlsplit(self.path)
            path = self.at = url.path.rstrip("/") or "/"
            self.query = {k: v[0] for k, v in parse_qs(url.query).items()}
            self.user, self.sess = self.current()
            self.form = {}
            if method == "POST":
                n = int(self.headers.get("Content-Length") or 0)
                limit = 4_000_000 if self.user and self.user["role"] == "staff" else 100_000  # staff upload photos
                if not 0 <= n <= limit: return self.page("Too large", "<p>That upload is too large.</p>", 413)
                self.form = {k: v[0] for k, v in parse_qs(self.rfile.read(n).decode(), keep_blank_values=True).items()}
                if self.sess and not hmac.compare_digest(self.form.get("csrf", ""), self.sess["csrf"]):
                    return self.page("Form expired", "<p>Go back, reload the page and try again.</p>", 403)
            for m, pattern, fn, need in ROUTES:
                match = re.fullmatch(pattern, path)
                if m == method and match:
                    if need and not self.user: return self.redirect("/login")
                    if need == "staff" and self.user["role"] != "staff":
                        return self.page("Staff only", "<p>You don't have access to this page.</p>", 403)
                    return fn(self, *match.groups())
            self.page("Not found", "<p>Nothing here.</p>", 404)
        except ValueError as ex:
            self.page("Couldn't do that", note(str(ex)), 400)
        except Exception:
            traceback.print_exc()
            self.page("Something went wrong", "<p>The error was logged. Try again.</p>", 500)
        finally:
            self.c.close()

    def current(self):
        try: tok = SimpleCookie(self.headers.get("Cookie", "")).get("sid")
        except CookieError: return None, None
        s = tok and self.c.execute("SELECT * FROM sessions WHERE token=? AND expires>?", (sha(tok.value), now())).fetchone()
        if not s: return None, None
        return self.c.execute("SELECT * FROM users WHERE id=?", (s["user_id"],)).fetchone(), s

    def send(self, code, body, headers=(), ctype="text/html; charset=utf-8", csp=None):
        b = body if isinstance(body, bytes) else body.encode()
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(b)))
        self.send_header("Content-Security-Policy", csp or "default-src 'self'; script-src 'self' https://unpkg.com; style-src 'self' 'unsafe-inline' https://unpkg.com; "
                         "img-src 'self' data: blob: https://tile.openstreetmap.org https://unpkg.com; "
                         "connect-src 'self' https://nominatim.openstreetmap.org; frame-ancestors 'none'")
        self.send_header("X-Content-Type-Options", "nosniff")
        self.send_header("Referrer-Policy", "same-origin")
        for k, v in headers: self.send_header(k, v)
        self.end_headers()
        self.wfile.write(b)

    def redirect(self, to, headers=()):
        self.send_response(303)
        self.send_header("Location", to)
        self.send_header("Content-Length", "0")
        for k, v in headers: self.send_header(k, v)
        self.end_headers()

    def csrf(self): return f'<input type="hidden" name="csrf" value="{e(self.sess["csrf"])}">' if self.sess else ""

