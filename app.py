def app(environ, start_response):
    """WSGI entry point (what Vercel runs). Drives the same handler class without a socket."""
    h = H.__new__(H)
    n = environ.get("CONTENT_LENGTH") or "0"
    body = environ["wsgi.input"].read(min(int(n), 4_000_001)) if n.isdigit() and int(n) > 0 else b""  # route() applies the per-role limit
    h.rfile, h.wfile, out, status = io.BytesIO(body), io.BytesIO(), [], []
    h.path = environ.get("PATH_INFO") or "/"
    if environ.get("QUERY_STRING"): h.path += "?" + environ["QUERY_STRING"]
    h.headers = {k[5:].replace("_", "-").title(): v for k, v in environ.items() if k.startswith("HTTP_")}
    h.headers["Content-Length"] = n
    h.send_response = lambda code, msg=None: status.append(f"{code} {HTTPStatus(code).phrase}")
    h.send_header = lambda k, v: out.append((k, v))
    h.end_headers = lambda: None
    h.route(environ["REQUEST_METHOD"])
    start_response(status[0], out)
    return [h.wfile.getvalue()]

