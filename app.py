def now(): return int(time.time())
def sha(s): return hashlib.sha256(s.encode()).hexdigest()
def when(ts): return datetime.fromtimestamp(ts, TZ).strftime("%Y-%m-%d %H:%M")
def money(c): return f"${c / 100:,.2f}"

class db:
    """One Postgres connection per request. `with c:` commits, or rolls back on error; `?` placeholders."""
    def __init__(self):
        # prepare_threshold=None: transaction poolers (Neon, Supabase) can't hold prepared statements
        self.conn = psycopg.connect(os.environ["DATABASE_URL"], row_factory=dict_row, prepare_threshold=None, connect_timeout=10)
    def execute(self, sql, args=None): return self.conn.execute(sql.replace("?", "%s"), args)
    def executemany(self, sql, rows): self.conn.cursor().executemany(sql.replace("?", "%s"), rows)
    def __enter__(self): return self
    def __exit__(self, err, *_): self.conn.rollback() if err else self.conn.commit()
    def close(self): self.conn.close()

def init():
    c = db()
    with c: c.conn.execute(SCHEMA)
    c.close()

def log(c, user_id, action, detail):
    c.execute("INSERT INTO audit(at,user_id,action,detail) VALUES(?,?,?,?)", (now(), user_id, action, detail))

def hash_pw(pw, salt=None):
    salt = salt or secrets.token_bytes(16)
    return salt.hex() + "$" + hashlib.scrypt(pw.encode(), salt=salt, n=2**14, r=8, p=1).hex()

def check_pw(pw, stored):
    return hmac.compare_digest(hash_pw(pw, bytes.fromhex(stored.split("$")[0])), stored)

def cents(s):
    try: d = Decimal(str(s).strip().lstrip("$"))
    except InvalidOperation: raise ValueError(f"Not an amount: {s!r}")
    if not d.is_finite() or d < 0: raise ValueError(f"Not an amount: {s!r}")
    return int(d.quantize(Decimal("0.01")) * 100)

def create_user(c, email, pw, name, phone, address="", role="customer", company=None, license_no=None, biz_status=None):
    email = email.strip().lower()
    if "@" not in email or len(pw) < 10 or not name.strip() or not phone.strip():
        raise ValueError("Enter a valid email, your name, a phone number and a password of 10+ characters.")
    try:
        with c:
            uid = c.execute("INSERT INTO users(email,pw,role,name,phone,address,company,license_no,biz_status,created_at) "
                            "VALUES(?,?,?,?,?,?,?,?,?,?) RETURNING id", (email, hash_pw(pw), role, name.strip(), phone.strip(),
                                                                         address.strip(), company, license_no, biz_status, now())).fetchone()["id"]
            return uid
    except psycopg.errors.UniqueViolation:
        raise ValueError("That email is already registered.")

def is_member(user):
    # Registering or depositing never grants access; only staff approval does.
    return bool(user) and user["biz_status"] == "approved"

def visible_products(c, user):
    hide = "" if is_member(user) else " AND wholesale_only=0"
    return c.execute(f"SELECT * FROM products WHERE active=1{hide} ORDER BY name").fetchall()

def place_order(c, user, qtys, name, phone, address, notes="", lat=None, lng=None, pin_address=None):
    """qtys: {product_id: qty}. Price and visibility come from the server, never the form."""
    ws = is_member(user)
    if not ws: raise ValueError("Ordering is for premium members. Your membership is activated once we confirm your deposit.")
    qtys = {pid: q for pid, q in qtys.items() if q > 0}
    if not qtys: raise ValueError("Enter a quantity for at least one product.")
    if not (name and phone and address): raise ValueError("Name, phone and delivery address are required.")
    if (lat is None) != (lng is None) or (lat is not None and not (-90 <= lat <= 90 and -180 <= lng <= 180)):
        raise ValueError("The map pin is invalid. Drag it again, or clear it and type the address.")
    pin_address = (pin_address or "").strip()[:300] if lat is not None else ""  # the map's address only means something with a pin
    pin_address = pin_address or None
    with c:  # one transaction: any failure rolls back every stock change
        items, total = [], 0
        for pid, qty in qtys.items():
            p = c.execute("SELECT * FROM products WHERE id=? AND active=1", (pid,)).fetchone()
            if not p or (p["wholesale_only"] and not ws): raise ValueError("A product in your order is not available.")
            if c.execute("UPDATE products SET stock=stock-? WHERE id=? AND stock>=?", (qty, pid, qty)).rowcount != 1:
                raise ValueError(f"Only {p['stock']} of {p['name']} in stock.")
            unit = p["wholesale_cents"] if ws else p["retail_cents"]
            items.append((pid, p["name"], qty, unit))
            total += qty * unit
        oid = c.execute("INSERT INTO orders(user_id,wholesale,total_cents,collect_cents,name,phone,address,notes,lat,lng,pin_address,created_at) "
                        "VALUES(?,?,?,?,?,?,?,?,?,?,?,?) RETURNING id",
                        (user["id"], int(ws), total, total, name, phone, address, notes, lat, lng, pin_address, now())).fetchone()["id"]
        c.executemany("INSERT INTO order_items VALUES(?,?,?,?,?)", [(oid, *i) for i in items])
        log(c, user["id"], "order.place", f"#{oid} {'wholesale' if ws else 'retail'} {money(total)}")
    return oid

def update_order(c, staff_id, oid, driver_id, status, payment, collect):
    if status not in STATUSES or payment not in PAYMENTS: raise ValueError("Unknown status or payment.")
    with c:
        o = c.execute("SELECT * FROM orders WHERE id=?", (oid,)).fetchone()
        if not o: raise ValueError("No such order.")
        if o["status"] == "cancelled": raise ValueError("Cancelled orders are final.")
        if driver_id and not c.execute("SELECT 1 FROM drivers WHERE id=?", (driver_id,)).fetchone():
            raise ValueError("No such driver.")
        if collect > o["total_cents"]: raise ValueError("Amount to collect can't exceed the order total.")
        if status == "delivered" and payment == "due_on_delivery":
            raise ValueError("Record how the customer paid (cash or transfer) before marking it delivered.")
        if status == "cancelled":
            for it in c.execute("SELECT product_id, qty FROM order_items WHERE order_id=?", (oid,)).fetchall():
                c.execute("UPDATE products SET stock=stock+? WHERE id=?", (it["qty"], it["product_id"]))
        new = {"driver_id": driver_id, "status": status, "payment": payment, "collect_cents": collect}
        c.execute("UPDATE orders SET driver_id=?, status=?, payment=?, collect_cents=? WHERE id=?",
                  (driver_id, status, payment, collect, oid))
        changes = [f"{k} {o[k]} -> {v}" for k, v in new.items() if o[k] != v]
        if changes: log(c, staff_id, "order.update", f"#{oid} " + ", ".join(changes))

def save_image(c, data_url, kind):
    """Store an image sent as a data: URL (the browser has already shrunk it). Returns the image id."""
    m = re.fullmatch(r"data:(image/(?:jpeg|png|webp));base64,([A-Za-z0-9+/=]+)", data_url or "")
    if not m: raise ValueError("Choose a photo (JPG, PNG or WebP) first.")
    raw = base64.b64decode(m[2])
    if len(raw) > 3_000_000: raise ValueError("That image is too large (3 MB max).")
    if not raw.startswith((b"\xff\xd8\xff", b"\x89PNG\r\n\x1a\n", b"RIFF")): raise ValueError("That file isn't a readable image.")
    return c.execute("INSERT INTO images(kind,mime,data,created_at) VALUES(?,?,?,?) RETURNING id",
                     (kind, m[1], raw, now())).fetchone()["id"]

def expire_receipts(c, staff_id):
    """Delete transfer receipts older than RECEIPT_DAYS. The order keeps its payment status and the audit log keeps the record."""
    with c:
        old = c.execute("SELECT o.id AS oid, i.id AS iid FROM orders o JOIN images i ON i.id=o.receipt_image_id "
                        "WHERE i.created_at < ?", (now() - RECEIPT_DAYS * 86400,)).fetchall()
        for r in old:
            c.execute("UPDATE orders SET receipt_image_id=NULL WHERE id=?", (r["oid"],))
            c.execute("DELETE FROM images WHERE id=?", (r["iid"],))
            log(c, staff_id, "order.receipt_expired", f"#{r['oid']} receipt deleted after {RECEIPT_DAYS} days")
    return len(old)

def country_codes(text):
    return sorted({x.upper() for x in re.findall(r"[A-Za-z]{2}", text or "")})

def pick_ad(c, placement, country):
    """A random active ad for this placement that may show in the visitor's country ('' when unknown, e.g. locally)."""
    if not ADS_ON: return None
    # Gambling ads are held: the product spec (FR-008, FR-018) keeps them off general-audience pages until an
    # age-checked adult area and a recorded approval exist. Every placement today is a general-audience page.
    fits = [a for a in c.execute("SELECT * FROM ads WHERE active=1 AND gambling=0 AND placement=?", (placement,)).fetchall()
            if (not a["countries"].strip() or country in country_codes(a["countries"])) and country not in country_codes(a["hide_countries"])]
    return random.choice(fits) if fits else None  # shortcut: equal rotation, no weights or impression counts; add them if advertisers pay per view

def save_ad(c, staff_id, aid, f):
    name, placement, link, code = f.get("name", "").strip(), f.get("placement", ""), f.get("link", "").strip(), f.get("code", "").strip()
    if not name or placement not in AD_PLACEMENTS: raise ValueError("Give the ad a name and choose where it shows.")
    old = aid and c.execute("SELECT * FROM ads WHERE id=?", (aid,)).fetchone()
    if aid and not old: raise ValueError("No such ad.")
    banner = bool(f.get("image_data") or (old and old["image_id"] and not code))
    if banner == bool(code): raise ValueError("Use either a banner image with a link, or ad-network code, not both.")
    if banner:
        u = urlsplit(link)
        if u.scheme != "https" or not u.netloc or len(link) > 2000: raise ValueError("The link must be a full https:// address.")
    if len(code) > 20_000: raise ValueError("That ad code is too long (20,000 characters max).")
    vals = (name[:200], placement, link if banner else None, code or None, int("gambling" in f),
            " ".join(country_codes(f.get("countries"))), " ".join(country_codes(f.get("hide_countries"))), int("active" in f))
    with c:
        if aid: c.execute("UPDATE ads SET name=?,placement=?,link=?,code=?,gambling=?,countries=?,hide_countries=?,active=? WHERE id=?", (*vals, aid))
        else: aid = c.execute("INSERT INTO ads(name,placement,link,code,gambling,countries,hide_countries,active,created_at) "
                              "VALUES(?,?,?,?,?,?,?,?,?) RETURNING id", (*vals, now())).fetchone()["id"]
        if f.get("image_data") or not banner:  # a new image replaces the old one; switching to code drops it
            new = save_image(c, f["image_data"], "ad") if f.get("image_data") else None
            c.execute("UPDATE ads SET image_id=? WHERE id=?", (new, aid))
            if old and old["image_id"]: c.execute("DELETE FROM images WHERE id=?", (old["image_id"],))
        log(c, staff_id, "ad.save", f"ad {aid} {vals[0]}: {placement}, {'banner ' + vals[2] if banner else 'network code'}, "
            f"countries {vals[5] or 'all'}, hidden in {vals[6] or 'none'}{', gambling' if vals[4] else ''}, {'active' if vals[7] else 'inactive'}")
    return aid

def wa_digits(phone):
    d = re.sub(r"\D", "", phone)
    if not 8 <= len(d) <= 15: raise ValueError("Phone must include the country code, e.g. +1 619 555 0100.")
    return d

def dispatch_text(o, items):
    lines = [f"NEW DELIVERY — #ORD-{o['id']}", "",
             f"Customer: {o['name']}", f"Phone: {o['phone']}", f"Address: {o['address']}"]
    if map_address(o): lines.append(f"Map pin address: {map_address(o)}")
    lines += ["Maps: " + maps_link(o), "",
              "Items: " + "; ".join(f"{i['qty']} x {i['name']}" for i in items),
              f"Total: {money(o['total_cents'])}"]
    if o["payment"] == "due_on_delivery":
        lines += [f"Collect: {money(o['collect_cents'])}", "Payment: due on delivery (customer pays you in cash or by transfer)"]
    else:
        lines += ["Collect: nothing", f"Payment: already {o['payment'].replace('_', ' ')}"]
    if o["notes"]: lines += ["", f"Instructions: {o['notes']}"]
    return "\n".join(lines + ["", "Please confirm receipt and reply with the delivery status."])

def map_address(o):
    """The map's address for the pin, only when it says something the typed address doesn't."""
    p = o.get("pin_address")
    return p if p and p.casefold().strip() != o["address"].casefold().strip() else None

def maps_link(o):
    # The member's exact pin when they dropped one, otherwise a search for the typed address. Opens in Google Maps.
    where = f"{o['lat']:.6f},{o['lng']:.6f}" if o.get("lat") is not None else o["address"]
    return "https://www.google.com/maps/search/?api=1&query=" + quote(where, safe="")

def wa_link(phone, text): return f"https://wa.me/{wa_digits(phone)}?text={quote(text, safe='')}"

def order_rows(c, where="true", args=(), limit=200):
    return c.execute(
        "SELECT o.*, u.email, d.name AS driver, string_agg(i.qty || ' x ' || i.name, ', ') AS items "
        "FROM orders o JOIN users u ON u.id=o.user_id JOIN order_items i ON i.order_id=o.id "
        f"LEFT JOIN drivers d ON d.id=o.driver_id WHERE {where} GROUP BY o.id, u.id, d.id ORDER BY o.id DESC LIMIT {int(limit)}",
        args).fetchall()

