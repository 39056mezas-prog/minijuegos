-- Run once against an empty Postgres database (Neon, Supabase, …), or run python3 app.py setup.

CREATE TABLE IF NOT EXISTS users(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email TEXT UNIQUE NOT NULL, pw TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'customer' CHECK(role IN ('customer','staff')),
  name TEXT NOT NULL, phone TEXT NOT NULL, address TEXT NOT NULL DEFAULT '',
  company TEXT, license_no TEXT,
  biz_status TEXT CHECK(biz_status IN ('pending','approved','rejected','revoked')),
  created_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS sessions(
  token TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users ON DELETE CASCADE, csrf TEXT NOT NULL, expires BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS products(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sku TEXT UNIQUE NOT NULL, name TEXT NOT NULL, description TEXT NOT NULL DEFAULT '',
  retail_cents INTEGER NOT NULL CHECK(retail_cents >= 0), wholesale_cents INTEGER NOT NULL CHECK(wholesale_cents >= 0),
  stock INTEGER NOT NULL DEFAULT 0 CHECK(stock >= 0),
  wholesale_only INTEGER NOT NULL DEFAULT 0, active INTEGER NOT NULL DEFAULT 1);
CREATE TABLE IF NOT EXISTS drivers(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, phone TEXT NOT NULL, active INTEGER NOT NULL DEFAULT 1);
CREATE TABLE IF NOT EXISTS orders(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users, wholesale INTEGER NOT NULL,
  status TEXT NOT NULL DEFAULT 'new', payment TEXT NOT NULL DEFAULT 'due_on_delivery',
  total_cents INTEGER NOT NULL, collect_cents INTEGER NOT NULL DEFAULT 0,
  name TEXT NOT NULL, phone TEXT NOT NULL, address TEXT NOT NULL, notes TEXT NOT NULL DEFAULT '',
  driver_id BIGINT REFERENCES drivers, created_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS order_items(
  order_id BIGINT NOT NULL REFERENCES orders, product_id BIGINT NOT NULL REFERENCES products,
  name TEXT NOT NULL, qty INTEGER NOT NULL CHECK(qty > 0), unit_cents INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS order_items_order ON order_items(order_id);
CREATE TABLE IF NOT EXISTS audit(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, at BIGINT NOT NULL, user_id BIGINT, action TEXT NOT NULL, detail TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS images(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, kind TEXT NOT NULL CHECK(kind IN ('product','receipt')), mime TEXT NOT NULL, data BYTEA NOT NULL,
  created_at BIGINT NOT NULL);
ALTER TABLE products ADD COLUMN IF NOT EXISTS image_id BIGINT REFERENCES images;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS receipt_image_id BIGINT REFERENCES images;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS lat DOUBLE PRECISION;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS lng DOUBLE PRECISION;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS pin_address TEXT;
ALTER TABLE images DROP CONSTRAINT IF EXISTS images_kind_check;
ALTER TABLE images ADD CONSTRAINT images_kind_check CHECK(kind IN ('product','receipt','ad'));
CREATE TABLE IF NOT EXISTS ads(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, placement TEXT NOT NULL CHECK(placement IN ('top','grid','side','pregame')),
  image_id BIGINT REFERENCES images, link TEXT, code TEXT, gambling INTEGER NOT NULL DEFAULT 0,
  countries TEXT NOT NULL DEFAULT '', hide_countries TEXT NOT NULL DEFAULT '', active INTEGER NOT NULL DEFAULT 1,
  clicks BIGINT NOT NULL DEFAULT 0, created_at BIGINT NOT NULL);
